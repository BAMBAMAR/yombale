/**
 * Retourne une photo de couverture par défaut HD choisie parmi les modèles de la catégorie.
 * La sélection est déterministe par boutique (via hash de son nom/id) pour qu'elle reste constante.
 */
export function getCategoryCoverPhoto(nom: string, categorie?: string | null): string {
  const catKey = (categorie || '').toLowerCase().trim()
  let pool = CATEGORY_COVER_PHOTOS[catKey]

  if (!pool || pool.length === 0) {
    // Recherche par mot clé si pas de correspondance exacte
    const foundKey = Object.keys(CATEGORY_COVER_PHOTOS).find(k => k !== 'default' && catKey.includes(k))
    pool = foundKey ? CATEGORY_COVER_PHOTOS[foundKey] : CATEGORY_COVER_PHOTOS['default']
  }

  // Calcul d'un hash déterministe pour choisir un modèle stable par boutique
  let hash = 0
  for (let i = 0; i < nom.length; i++) {
    hash = (hash << 5) - hash + nom.charCodeAt(i)
    hash |= 0
  }
  const index = Math.abs(hash) % pool.length
  return pool[index]
}
